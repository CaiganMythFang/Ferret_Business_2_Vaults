onEvent('item.right_click', event => {
	
  if (event.item.id == 'tfb2:blindbox_chipped_cheap1') {
	  
	event.server.runCommandSilent('loot give ' + event.getEntity() + ' loot tfb2:chipped/chipped_cheap1');
	event.player.tell(Text.lightPurple("You open up an Crab Weird Blind Box!"));
	  
	if (!event.player.isCreativeMode()) { //if creative mode dont consume; not necessary
	  event.item.setCount(event.item.getCount() - 1)
	}
  }
});

