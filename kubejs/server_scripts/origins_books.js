// Wolf
onEvent('item.right_click', event => {
	
  if (event.item.id == 'tfb2:origins_book_wolf') {
	  
	event.server.runCommandSilent('origin set ' + event.getEntity() + ' origins:origin tfb2:wolf');
	event.player.tell(Text.lightPurple("You have set your species to : Wolf!"));
  }
});

