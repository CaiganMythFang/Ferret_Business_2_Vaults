// Vault - Raw Vault Token
onEvent('item.registry', event => {
    event.create('tfb2:token_raw')
        .displayName('Token - Raw Vault')
        .maxStackSize(64)
        .rarity(RARITY_UNCOMMON)
        .group('tfb2')
});

onEvent('item.tooltip', tooltip => {
tooltip.addAdvanced('tfb2:token_raw', (item, advanced, text) => {
    text.add(1, [Text.of('A').obfuscated(), Text.of('Token').lightPurple(), Text.of('A').obfuscated()])
    text.add(2, [Text.of('A token representing a magical coded link into the').darkPurple()])
    text.add(3, [Text.of('FOP Game Data Servers. Spend in the Shop Catalogue!').darkPurple()])
    })
});

