// Research Icons


// Pirate Broadcast
onEvent('item.registry', event => {
    event.create('tfb2:research_pirate')
        .displayName('Research DLC Icon - Pirate Broadcast')
        .maxStackSize(1)
        .rarity(RARITY_RARE)
        .group('misc')
});

onEvent('item.tooltip', tooltip => {
tooltip.addAdvanced('tfb2:research_pirate', (item, advanced, text) => {
    text.add(1, [Text.of('An Icon for the Pirate Broadcast Research DLC Catagory').darkPurple()])
    })
});

