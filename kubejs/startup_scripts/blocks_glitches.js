// Glitched Vault Cobble
onEvent('block.registry', event => {
  event.create('tfb2:glitched_vault_cobble')
  	   .material('dragon_egg')
       .hardness(0.5)
       .displayName('Glitched Vault Cobblestone') 
       .tagItem('tfb2:glitched_block')
  })
  
onEvent('item.tooltip', tooltip => {
tooltip.addAdvanced('tfb2:glitched_vault_cobble', (item, advanced, text) => {
    text.add(1, [Text.of('A').obfuscated(), Text.of('Glitched').lightPurple(), Text.of('A').obfuscated()])
    text.add(2, [Text.of('A glitched block, useful to The Ferret Business').darkPurple()])
    })
});

